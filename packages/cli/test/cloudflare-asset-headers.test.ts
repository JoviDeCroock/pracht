import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { afterEach, describe, expect, it } from "vitest";

import {
  createCloudflareAssetHeadersFile,
  writeCloudflareAssetHeaders,
} from "../src/cloudflare-asset-headers.ts";

const tempDirs: string[] = [];

function createApp(): { clientDir: string; publicDir: string } {
  const root = mkdtempSync(join(tmpdir(), "pracht-cf-asset-headers-"));
  tempDirs.push(root);
  const clientDir = join(root, "dist/client");
  const publicDir = join(root, "public");
  mkdirSync(clientDir, { recursive: true });
  mkdirSync(publicDir, { recursive: true });
  return { clientDir, publicDir };
}

afterEach(() => {
  for (const dir of tempDirs.splice(0)) rmSync(dir, { force: true, recursive: true });
});

describe("Cloudflare asset _headers", () => {
  it("gives hashed assets the immutable policy and the default security headers", () => {
    expect(createCloudflareAssetHeadersFile().file).toMatchInlineSnapshot(`
      "# Generated by \`pracht build\` for Cloudflare's static-assets layer.
      # Add public/_headers to replace it with your own rules.
      /assets/*
        cache-control: public, max-age=31536000, immutable
        permissions-policy: accelerometer=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()
        referrer-policy: strict-origin-when-cross-origin
        x-content-type-options: nosniff
        x-frame-options: SAMEORIGIN
      "
    `);
  });

  it("keeps build headers for files under /assets/ that the Worker would have applied", () => {
    const { file, skipped } = createCloudflareAssetHeadersFile({
      "/": {},
      "/about": { "Cache-Control": "private" },
      "/assets/search.json": {
        "cache-control": "public, max-age=0, must-revalidate",
        "content-type": "application/json",
      },
      "/assets/:slug": { "cache-control": "no-store" },
    });

    // Only /assets/ paths skip the Worker; everything else keeps its runtime
    // headers there. The exact rule follows the wildcard and detaches the
    // wildcard's cache-control, or Cloudflare would append the two values.
    expect(file).not.toContain("/about");
    expect(file.split("/assets/search.json\n")[1]).toBe(
      [
        "  ! cache-control",
        "  cache-control: public, max-age=0, must-revalidate",
        "  content-type: application/json",
        "",
      ].join("\n"),
    );
    expect(file.indexOf("/assets/*")).toBeLessThan(file.indexOf("/assets/search.json"));
    expect(skipped).toEqual(["/assets/:slug"]);
  });

  it("writes dist/client/_headers when the app ships none", () => {
    const { clientDir, publicDir } = createApp();

    expect(writeCloudflareAssetHeaders(clientDir, publicDir)).toEqual({
      skipped: [],
      warning: null,
    });
    expect(readFileSync(join(clientDir, "_headers"), "utf-8")).toBe(
      createCloudflareAssetHeadersFile().file,
    );
  });

  it("leaves an app-owned public/_headers in place and says what it must cover", () => {
    const { clientDir, publicDir } = createApp();
    const own = "/*\n  X-Robots-Tag: noindex\n";
    writeFileSync(join(publicDir, "_headers"), own);
    // Vite has already copied the public file into the client output.
    writeFileSync(join(clientDir, "_headers"), own);

    const { warning } = writeCloudflareAssetHeaders(clientDir, publicDir, {}, "static");

    expect(warning).toContain("static/_headers exists");
    expect(warning).toContain("/assets/*");
    expect(readFileSync(join(clientDir, "_headers"), "utf-8")).toBe(own);
  });

  it("does not need a public directory", () => {
    const { clientDir } = createApp();

    expect(writeCloudflareAssetHeaders(clientDir, join(clientDir, "missing")).warning).toBeNull();
    expect(existsSync(join(clientDir, "_headers"))).toBe(true);
  });
});
