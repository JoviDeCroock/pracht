import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { applyDefaultSecurityHeaders } from "@pracht/core";
import type { PrachtAdapterBuildContext } from "@pracht/vite-plugin";

/**
 * Vite's content-hashed output directory. Node and Netlify already serve it
 * with the immutable policy below; this keeps Cloudflare in step.
 */
export const CLOUDFLARE_HASHED_ASSET_PATTERN = "/assets/*";

const HASHED_ASSET_PREFIX = "/assets/";
const IMMUTABLE_ASSET_CACHE_CONTROL = "public, max-age=31536000, immutable";

type HeadersManifest = Record<string, Record<string, string>>;

export interface CloudflareAssetHeadersResult {
  /** Build-header entries that `_headers` cannot express as an exact path. */
  skipped: string[];
  /** Why no file was generated, when the app ships its own. */
  warning: string | null;
}

/**
 * Cloudflare's static-assets layer answers every file with
 * `Cache-Control: public, max-age=0, must-revalidate`, so without a rule the
 * browser revalidates each content-hashed chunk on every visit. Its `_headers`
 * file is applied by that layer itself — to requests it serves directly (the
 * `"!/assets/*"` exclusion in `run_worker_first`) and to the Worker's own
 * `env.ASSETS.fetch()` — so one rule covers both routings. The security
 * headers are the ones the Worker would otherwise add, because a request that
 * skips the Worker gets nothing else.
 *
 * Build-time headers for files under `/assets/` (a content artifact's
 * `must-revalidate`, say) are what the Worker applies on top, so each gets an
 * exact rule after the wildcard. The layer applies matching rules in file
 * order and appends a header an earlier rule already set, which is why the
 * exact rule detaches (`! name`) the wildcard's value before setting its own.
 */
export function createCloudflareAssetHeadersFile(headersManifest: HeadersManifest = {}): {
  file: string;
  skipped: string[];
} {
  const wildcard = applyDefaultSecurityHeaders(
    new Headers({ "cache-control": IMMUTABLE_ASSET_CACHE_CONTROL }),
  );
  const lines = [
    "# Generated by `pracht build` for Cloudflare's static-assets layer.",
    "# Add public/_headers to replace it with your own rules.",
    CLOUDFLARE_HASHED_ASSET_PATTERN,
  ];
  for (const [name, value] of wildcard) lines.push(`  ${name}: ${value}`);

  const skipped: string[] = [];
  for (const pathname of Object.keys(headersManifest).sort()) {
    if (!pathname.startsWith(HASHED_ASSET_PREFIX)) continue;
    const entries = Object.entries(headersManifest[pathname]!);
    if (entries.length === 0) continue;
    if (!isExactCloudflareRulePath(pathname) || entries.some(([, value]) => /[\r\n]/.test(value))) {
      skipped.push(pathname);
      continue;
    }
    lines.push(pathname);
    for (const [name] of entries) {
      if (wildcard.has(name)) lines.push(`  ! ${name.toLowerCase()}`);
    }
    for (const [name, value] of entries) lines.push(`  ${name.toLowerCase()}: ${value}`);
  }
  return { file: `${lines.join("\n")}\n`, skipped };
}

/**
 * `*` is a splat and a `:`-leading segment a placeholder in `_headers`, and
 * whitespace would end the rule line, so such a path cannot be matched exactly.
 */
function isExactCloudflareRulePath(pathname: string): boolean {
  return (
    /^\/[\x21-\x7e]*$/.test(pathname) &&
    !pathname.includes("*") &&
    !pathname.split("/").some((segment) => segment.startsWith(":"))
  );
}

/**
 * Write `dist/client/_headers` unless the app ships its own from `public/`,
 * which Vite has already copied there and which stays authoritative.
 */
export function writeCloudflareAssetHeaders(
  clientDir: string,
  publicDir: string,
  headersManifest: HeadersManifest = {},
  publicDirLabel = "public",
): CloudflareAssetHeadersResult {
  if (publicDir && existsSync(join(publicDir, "_headers"))) {
    return {
      skipped: [],
      warning:
        `${publicDirLabel}/_headers exists, so pracht build did not generate dist/client/_headers. ` +
        `Make sure it gives ${CLOUDFLARE_HASHED_ASSET_PATTERN} ` +
        `"Cache-Control: ${IMMUTABLE_ASSET_CACHE_CONTROL}" and pracht's default security headers.`,
    };
  }
  const { file, skipped } = createCloudflareAssetHeadersFile(headersManifest);
  writeFileSync(join(clientDir, "_headers"), file, "utf-8");
  return { skipped, warning: null };
}

/**
 * `cloudflareAdapter().finalizeBuild`: the static-assets `_headers` file, the
 * ISG manifest the Worker reads through the assets binding, and the
 * `dist/server/worker.js` entry `wrangler deploy` runs.
 */
export async function finalizeCloudflareBuild(context: PrachtAdapterBuildContext): Promise<void> {
  const { clientDir, isgManifest, root, serverEntry } = context;

  if (Object.keys(isgManifest).length > 0) {
    // Only the Cloudflare worker runtime reads the manifest from the static
    // assets (via readPrachtISGManifest). On other targets the client dir is
    // served publicly, so the CLI keeps it in dist/server only.
    mkdirSync(resolve(clientDir, "_pracht"), { recursive: true });
    writeFileSync(
      resolve(clientDir, "_pracht/isg.json"),
      `${JSON.stringify(isgManifest, null, 2)}\n`,
      "utf-8",
    );
  }

  const assetHeaders = writeCloudflareAssetHeaders(
    clientDir,
    context.publicDir,
    { ...context.headersManifest },
    context.publicDirLabel,
  );
  if (assetHeaders.warning) context.warn(`\n  Warning: ${assetHeaders.warning}\n`);
  if (assetHeaders.skipped.length > 0) {
    context.warn(
      `\n  Warning: dist/client/_headers cannot match ${assetHeaders.skipped.join(", ")} ` +
        "exactly, so Cloudflare serves them with the /assets/* immutable policy instead of " +
        "their build headers. Rename them or keep them out of /assets/.\n",
    );
  }

  if (serverEntry.cloudflareWorkersCacheEnabled === true && context.onDemandPages.length > 0) {
    context.log(
      `\n  ISG via Workers Caching: ${context.onDemandPages.length} route(s) render on demand and revalidate at the edge. Requires "cache": { "enabled": true } in wrangler config.\n`,
    );
  }

  // The adapter builds the Worker entry to dist/server/worker.js, next to the
  // Cloudflare plugin's generated wrangler.json. workerd accepts only handlers
  // and entrypoint classes as that module's exports, so when it re-exports
  // anything else from the app's Worker module (or a custom entry emitted only
  // server.js, whose build metadata workerd rejects), write a thin entry
  // re-exporting just those from server.js instead.
  const workerEntryPath = resolve(root, "dist/server/worker.js");
  const builtWorkerEntry = existsSync(workerEntryPath);
  const legacyEntrypointNames: unknown[] = Array.isArray(
    serverEntry.cloudflareWorkerEntrypointNames,
  )
    ? serverEntry.cloudflareWorkerEntrypointNames
    : [];
  const deployExports: Array<[string, unknown]> = builtWorkerEntry
    ? Object.entries(await import(pathToFileURL(workerEntryPath).href))
    : Object.entries(serverEntry).filter(([name]) => legacyEntrypointNames.includes(name));
  const { entrypointNames, droppedNames } = splitCloudflareWorkerExports(deployExports);
  if (!builtWorkerEntry || droppedNames.length > 0) {
    const deployEntryLines = [
      ...(entrypointNames.length > 0
        ? [`export { ${entrypointNames.join(", ")} } from "./server.js";`]
        : []),
      'export { default } from "./server.js";',
      "",
    ];
    writeFileSync(workerEntryPath, deployEntryLines.join("\n"), "utf-8");
  }
  if (droppedNames.length > 0) {
    context.log(
      `\n  Left ${droppedNames.join(", ")} out of dist/server/worker.js: a Worker module may only export handlers and entrypoint classes.`,
    );
  }

  context.log("\n  Cloudflare worker → dist/server/worker.js\n");
  context.log(describeCloudflareDeploy(root));
}

/**
 * Splits a Worker module's exports into what workerd accepts beside `default`
 * (handlers and entrypoint classes: functions and non-null objects) and what
 * it rejects at startup (every other value).
 */
export function splitCloudflareWorkerExports(exports: Iterable<[string, unknown]>): {
  entrypointNames: string[];
  droppedNames: string[];
} {
  const entrypointNames: string[] = [];
  const droppedNames: string[] = [];
  for (const [name, value] of exports) {
    if (name === "default") continue;
    if (typeof value === "function" || (typeof value === "object" && value !== null)) {
      entrypointNames.push(name);
    } else {
      droppedNames.push(name);
    }
  }
  return { entrypointNames, droppedNames };
}

/**
 * How to deploy a Cloudflare build. The Cloudflare Vite plugin writes
 * dist/server/wrangler.json plus a `.wrangler/deploy/config.json` redirect
 * that plain `wrangler deploy` follows. The adapter removes the redirect when
 * the user's config defines named environments and the build selected none,
 * so `wrangler deploy --env <name>` keeps reading the user's own config.
 */
export function describeCloudflareDeploy(root: string): string {
  const generated = readGeneratedWranglerEnvironments(resolve(root, "dist/server/wrangler.json"));
  if (generated && existsSync(resolve(root, ".wrangler/deploy/config.json"))) {
    return "  Deploy with: wrangler deploy (uses the generated dist/server/wrangler.json)\n";
  }
  if (generated && generated.defined.length > 0 && !generated.target) {
    return (
      "  Deploy with: wrangler deploy --env <name> (reads your wrangler config, whose main must be dist/server/worker.js),\n" +
      "  or rebuild with CLOUDFLARE_ENV=<name> to deploy the generated dist/server/wrangler.json.\n"
    );
  }
  return "  Deploy with: wrangler deploy\n";
}

function readGeneratedWranglerEnvironments(
  file: string,
): { defined: unknown[]; target: unknown } | undefined {
  if (!existsSync(file)) return undefined;
  try {
    const config = JSON.parse(readFileSync(file, "utf-8")) as {
      definedEnvironments?: unknown;
      targetEnvironment?: unknown;
    };
    return {
      defined: Array.isArray(config.definedEnvironments) ? config.definedEnvironments : [],
      target: config.targetEnvironment,
    };
  } catch {
    return undefined;
  }
}
